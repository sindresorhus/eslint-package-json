for (const [command, short, long, stopsFixing] of aliases) {
	test(`${command} -${short} fixes to --${long}`, () => {
		const linter = new Linter();
		const followingFlag = stopsFixing ? `-${short}` : `--${long}`;
		const cases = [
			[`${command} -${short} operand`, `${command} --${long} operand`],
			[`${command} '-${short}' operand`, `${command} '--${long}' operand`],
			[`${command} -${short} -${short}`, `${command} --${long} ${followingFlag}`],
			[`${command} --${long} -${short}`, `${command} --${long} ${followingFlag}`],
		];

		const results = cases.map(([script]) => {
			const code = JSON.stringify({scripts: {test: script}});
			const [message] = linter.verify(code, config);
			const {output} = linter.verifyAndFix(code, config);
			return {
				messageId: message.messageId,
				firstFix: message.fix ? JSON.parse(message.fix.text) : script,
				script: JSON.parse(output).scripts.test,
				fixedAgain: linter.verifyAndFix(output, config).fixed,
			};
		});
		assert.deepEqual(results, cases.map(([, expected]) => ({
			messageId: 'no-short-flags-in-scripts',
			firstFix: expected,
			script: expected,
			fixedAgain: false,
		})));
	});
}

