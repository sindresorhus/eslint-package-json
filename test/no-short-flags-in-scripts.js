test('partial fixes leave flag-shaped option values untouched and converge in one round', () => {
	const linter = new Linter();
	const code = '{"scripts":{"test":"tsc -p -w && eslint -c -v && node -e \'-c\' && prettier -h -w"}}';
	const [message] = linter.verify(code, config);
	assert.equal(JSON.parse(message.fix.text), 'tsc --project -w && eslint --config -v && node --eval \'-c\' && prettier --help -w');
	const {output} = linter.verifyAndFix(code, config);
	assert.equal(linter.verify(output, config).length, 1);
	assert.equal(linter.verifyAndFix(output, config).fixed, false);
});

test('shell parameter expansion is never rewritten', () => {
	const linter = new Linter();
	// eslint-disable-next-line no-template-curly-in-string -- This is shell parameter expansion, not JavaScript interpolation.
	const code = '{"scripts":{"test":"echo ${UNSET_VALUE:-; prettier -w . }"}}';
	const [message] = linter.verify(code, config);
	assert.equal(message.messageId, 'no-short-flags-in-scripts');
	assert.equal(message.fix, undefined);
});
